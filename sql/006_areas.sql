  company_id uuid not null references companies on delete cascade,
  suburb text not null,
  area text not null,
  primary key (company_id, suburb)
);
alter table suburb_areas enable row level security;
drop policy if exists company_isolation on suburb_areas;
create policy company_isolation on suburb_areas
  using (company_id in (select my_company_ids()))
  with check (company_id in (select my_company_ids()));
grant select, insert, update, delete on suburb_areas to authenticated;

